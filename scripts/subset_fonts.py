"""Cuts the font files down to the characters the site actually uses and writes assets/fonts.css.

Google's latin-ext file for Unbounded is 115 KB, and Azerbaijani pages need it for a handful of
letters (ə Ə İ ş Ş ğ). Every file keeps the characters that appear in the built pages and scripts;
the latin files also always keep printable ASCII and Latin-1, so ordinary new text never falls back.

Inputs:  fonts/src/fonts.css        @font-face rules as Google serves them (urls point to /fonts/<file>)
         fonts/src/*.woff2          the original files (latin, latin-ext, cyrillic, cyrillic-ext)
Outputs: fonts/*.woff2              subsets
         assets/fonts.css           the rules with each -ext face's unicode-range narrowed to its subset
         fonts/subset.json          the characters each subset covers (scripts/check_site.py reads it)

Run after build.py whenever new text may use new letters:  python scripts/subset_fonts.py && python build.py
Needs fonttools and brotli (pip install fonttools brotli).
"""
import glob
import json
import os
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "fonts", "src")
ALWAYS = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100))  # printable ASCII and Latin-1 stay in the latin files


def used_chars():
    """Every character in the built pages and the scripts (the game draws station names on a canvas)."""
    files = [f for f in glob.glob(os.path.join(ROOT, "**", "*.html"), recursive=True)
             if not os.path.relpath(f, ROOT).replace(os.sep, "/").startswith(("tests/", "content/", "node_modules/"))]
    files += glob.glob(os.path.join(ROOT, "assets", "*.js"))
    chars = set()
    for f in files:
        with open(f, encoding="utf-8") as fh:
            chars |= {ord(c) for c in fh.read()}
    return chars


def parse_range(text):
    cps = set()
    for part in text.split(","):
        part = part.strip().upper().removeprefix("U+")
        if "-" in part:
            a, b = part.split("-")
            cps |= set(range(int(a, 16), int(b, 16) + 1))
        elif "?" in part:
            cps |= set(range(int(part.replace("?", "0"), 16), int(part.replace("?", "F"), 16) + 1))
        else:
            cps.add(int(part, 16))
    return cps


def to_range(cps):
    return ", ".join(f"U+{c:04X}" for c in sorted(cps))


def main():
    with open(os.path.join(SRC, "fonts.css"), encoding="utf-8") as f:
        css = f.read()
    chars = used_chars()
    manifest = {}
    out = css

    for block in re.findall(r"@font-face \{.*?\}", css, re.S):
        url = re.search(r"url\(/fonts/([^)]+)\)", block).group(1)
        rng = parse_range(re.search(r"unicode-range: ([^;]+);", block).group(1))
        cmap = set(TTFont(os.path.join(SRC, url)).getBestCmap())
        keep = (chars | ALWAYS) & rng & cmap
        unsupported = "".join(chr(c) for c in sorted((chars & rng) - cmap))  # used, but this font has no glyph for it
        target = os.path.join(ROOT, "fonts", url)
        if url in manifest and keep:  # variable fonts: one file serves several weights, subset it once
            out = out.replace(block, re.sub(r"unicode-range: [^;]+;", f"unicode-range: {to_range(keep)};", block))
            continue
        if not keep:  # the site uses nothing from this file: drop the face
            out = out.replace(block + "\n", "").replace(block, "")
            if os.path.exists(target):
                os.remove(target)
            manifest[url] = {"chars": "", "unsupported": unsupported}
            continue
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = ["*"]
        opts.notdef_outline = True
        font = TTFont(os.path.join(SRC, url))
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=keep)
        sub.subset(font)
        font.flavor = "woff2"
        font.save(target)
        new_block = re.sub(r"unicode-range: [^;]+;", f"unicode-range: {to_range(keep)};", block)
        out = out.replace(block, new_block)
        if url in manifest:  # variable fonts: one file serves several weights, subset it once
            out = out.replace(block, new_block)
            continue
        manifest[url] = {"chars": "".join(chr(c) for c in sorted(keep)), "unsupported": unsupported}
        print(f"{url}: {len(keep)} characters, {os.path.getsize(os.path.join(SRC, url)) // 1024} KB -> {os.path.getsize(target) // 1024} KB")

    out = out.replace("/* Self-hosted fonts", "/* Generated by scripts/subset_fonts.py from fonts/src/fonts.css; do not edit.\n   Self-hosted fonts", 1)
    with open(os.path.join(ROOT, "assets", "fonts.css"), "w", encoding="utf-8", newline="\n") as f:
        out = re.sub(r"/\* [a-z-]+ \*/\n(?=/\*|$)", "", out)  # comments left without a face
        f.write(re.sub(r"\n{3,}", "\n\n", out))
    with open(os.path.join(ROOT, "fonts", "subset.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=1, sort_keys=True)
        f.write("\n")


if __name__ == "__main__":
    main()
